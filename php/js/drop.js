window.onload = function () {
	
	//Get html elements
	var typefw = document.getElementById("typefw");
	var typefp = document.getElementById("typefp");	
	var sizefp = document.getElementById("sizefp");
	var tqm = document.getElementById("tqm");
	
	//Load countries
	for (var typeofwork in workselection) {
		typefw.options[typefw.options.length] = new Option(typeofwork, typeofwork);
	}
	
	//County Changed
	typefw.onchange = function () {
		 
		 typefp.length = 1; // remove all options bar first
		 sizefp.length = 1; // remove all options bar first
		 tqm.length = 1; // remove all options bar first
		 
		 if (this.selectedIndex < 1)
			 return; // done
		 
		 for (var typeofpipes in workselection[this.value]) {
			 typefp.options[typefp.options.length] = new Option(typeofpipes, typeofpipes);
		 }
	}
	
	//typeofpipes Changed
	typefp.onchange = function () {		 
		 
		 sizefp.length = 1; // remove all options bar first
		 tqm.length = 1; // remove all options bar first
		 
		 if (this.selectedIndex < 1)
			 return; // done
		 
		 for (var sizeofpipe in workselection[typefw.value][this.value]) {
			 sizefp.options[sizefp.options.length] = new Option(sizeofpipe, sizeofpipe);
		 }
	}
	
	//sizeofpipe Changed
	sizefp.onchange = function () {
		tqm.length = 1; // remove all options bar first
		
		if (this.selectedIndex < 1)
			return; // done
		
		var zips = workselection[typefw.value][typefp.value][this.value];
		for (var i = 0; i < zips.length; i++) {
			tqm.options[tqm.options.length] = new Option(zips[i], zips[i]);
		}
	}	
}